<?php

$a = 10;
$b = 2;
$result = $a * $b;
echo $result . "<br>";

//Penjumlahan
$a += $b; // nilai a = 12
echo $a . "<br>";
//Pengurangan
$a -= $b; // nilai a = 12 - 2 = 10
echo $a . "<br>";
//Perkalian
$a *= $b; // nilai a = 10 * 2 = 20
echo $a . "<br>";

// nilai a akan terus berubah seperti terakhir kali di operasikan
//Pembagian
$a /= $b; // nilai a = 20 / 2 = 10
echo $a . "<br>";

